"""
gen_fixed_lut.py -- bit-exact model of the fixed-point bin LUT (the chosen design),
plus the table file and test vectors for the Verilog testbench.

Run:
    python gen_fixed_lut.py  <output folder for .mem/.vh files>

Number formats (all integers in hardware):
    V      27-bit signed,  Q7.19 in mV      (1 LSB = 2^-19 mV, range -128 .. +128 mV)
    u      V + 64 mV                         (u = V + 2^25)
    index  u[25:18]   8 bits -> 256 bins of 0.5 mV, covering -64 .. +64 mV
    frac   u[17:0]   18 bits -> position inside the bin, 0 .. 2^18-1
    b      24-bit signed, 22 fraction bits   value of the line at the bin start
    dy     18-bit signed, 20 fraction bits   how much the line rises across the whole bin
    y      18-bit unsigned UQ0.18            output gate value, 0 .. 1-2^-18

    y = b + dy * frac / 2^18      (rounded to 18 fraction bits, clamped to 0 .. 2^18-1)

Table address = {curve_sel (4 bits), index (8 bits)} -> 4096 words of 42 bits = {b, dy}.
curve_sel: 0 hNa, 1 mNa, 2 mP, 3 mCaF, 4 hCaF, 5 mCaS, 6 hCaS, 7 mh, 8 mK1, 9 hK1, 10-15 unused (all zero).
"""
import os, sys
import numpy as np
import lut_model as L

V_FRAC = 19            # V fraction bits (mV)
B_FRAC = 22            # b fraction bits
DY_FRAC = 20           # dy fraction bits
NBINS = 256
BIN_MV = 0.5

def to_signed_int(x, bits, frac):
    # real number -> nearest integer in a signed fixed-point format (saturate at the ends)
    v = int(round(x * 2 ** frac))
    lo, hi = -(2 ** (bits - 1)), 2 ** (bits - 1) - 1
    return max(lo, min(hi, v))

def make_tables():
    # 16 curve slots x 256 bins; returns two lists of python ints: b_int[addr], dy_int[addr]
    b_int = [0] * 4096
    dy_int = [0] * 4096
    lo = (-64.0 + BIN_MV * np.arange(NBINS)) / 1000.0     # bin start, volts
    hi = lo + BIN_MV / 1000.0
    for sel, (name, f) in enumerate(L.CURVES.items()):
        b, m = L.bin_coeffs(f, lo, hi, "lin_best")
        for i in range(NBINS):
            addr = sel * 256 + i
            b_int[addr] = to_signed_int(b[i], 24, B_FRAC)
            dy_int[addr] = to_signed_int(m[i] * (hi[i] - lo[i]), 18, DY_FRAC)
    return b_int, dy_int

def lut_hw(v_int, sel, b_int, dy_int):
    # EXACTLY what the Verilog does, step by step, on integers
    u = v_int + (1 << 25)                     # add 64 mV
    if u < 0:                                 # below -64 mV -> first bin, start
        u = 0
    if u > (1 << 26) - 1:                     # at/above +64 mV -> last bin, end
        u = (1 << 26) - 1
    index = u >> 18
    frac = u & ((1 << 18) - 1)
    addr = sel * 256 + index
    prod = frac * dy_int[addr]                # 2^-38 units
    total = prod + (b_int[addr] << 16)        # b moved to 2^-38 units
    y = (total + (1 << 19)) >> 20             # round to 2^-18 units (>> is floor, like taking the bits)
    if y < 0:
        y = 0
    if y > (1 << 18) - 1:
        y = (1 << 18) - 1
    return y

def main():
    out = sys.argv[1] if len(sys.argv) > 1 else "."
    os.makedirs(out, exist_ok=True)
    b_int, dy_int = make_tables()

    # ---- table file for $readmemh: one 42-bit word {b, dy} per line, 11 hex digits
    with open(os.path.join(out, "lut_fixed.mem"), "w") as fo:
        for a in range(4096):
            word = ((b_int[a] & 0xFFFFFF) << 18) | (dy_int[a] & 0x3FFFF)
            fo.write(f"{word:011X}\n")

    # ---- human-readable table CSV (docx-like: one block per curve)
    tables_dir = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "tables")
    with open(os.path.join(tables_dir, "LUT_fixed256_linbest.csv"), "w") as fo:
        fo.write("# GENERATED by gen_fixed_lut.py. Fixed-point 256-bin LUT, bins of 0.5 mV from -64 mV.\n")
        fo.write("curve,bin,V_start_mV,b_int(Q1.22),dy_int(Q-2.20),b_real,dy_real\n")
        for sel, name in enumerate(L.CURVES):
            for i in range(NBINS):
                a = sel * 256 + i
                fo.write(f"{name},{i},{-64 + BIN_MV*i:.1f},{b_int[a]},{dy_int[a]},{b_int[a]/2**B_FRAC:.8f},{dy_int[a]/2**DY_FRAC:.8f}\n")

    # ---- test vectors
    rnd = np.random.default_rng(460)
    tests = []
    for sel in range(16):
        vs = []
        if sel < len(L.CURVES):
            for i in range(NBINS):                       # every bin edge, edge-1, edge+1, middle
                edge = (i << 18) - (1 << 25)
                vs += [edge - 1, edge, edge + 1, edge + (1 << 17)]
            lo_i = int(L.V_LO * 1000 * 2 ** V_FRAC)
            hi_i = int(L.V_HI * 1000 * 2 ** V_FRAC)
            vs += [int(x) for x in rnd.integers(lo_i, hi_i, 2000)]            # real range
            vs += [int(x) for x in rnd.integers(-(1 << 26), 1 << 26, 200)]    # anywhere
        vs += [-(1 << 26), (1 << 26) - 1, -(1 << 25) - 1, -(1 << 25), (1 << 25) - 1, 1 << 25, 0]
        for v in vs:
            v = max(-(1 << 26), min((1 << 26) - 1, v))
            tests.append((sel, v, lut_hw(v, sel, b_int, dy_int)))

    with open(os.path.join(out, "tv_in.mem"), "w") as fo:     # {sel[3:0], v[26:0]} = 31 bits
        for sel, v, y in tests:
            fo.write(f"{(sel << 27) | (v & ((1 << 27) - 1)):08X}\n")
    with open(os.path.join(out, "tv_out.mem"), "w") as fo:    # expected y, 18 bits
        for sel, v, y in tests:
            fo.write(f"{y:05X}\n")
    with open(os.path.join(out, "tb_params.vh"), "w") as fo:
        fo.write(f"`define N_TESTS {len(tests)}\n")

    # ---- accuracy of the bit-exact model vs the true curves (real V range)
    print(f"{len(tests)} test vectors written to {out}")
    grid_int = np.round(L.GRID * 1000 * 2 ** V_FRAC).astype(np.int64)[::20]   # 20,001 points
    print("bit-exact max error vs true curve over the real V range (target 7.12e-4):")
    for sel, (name, f) in enumerate(L.CURVES.items()):
        ys = np.array([lut_hw(int(v), sel, b_int, dy_int) for v in grid_int]) / 2 ** 18
        err = np.max(np.abs(ys - f(grid_int / 2 ** V_FRAC / 1000.0)))
        print(f"  {name:5s} {err:.3e}")

if __name__ == "__main__":
    main()
